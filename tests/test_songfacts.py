def test_a_youtube_description_names_its_label_and_year():
    art_track = (
        "Provided to YouTube by Sony Music Entertainment\n\nFlowers · Miley Cyrus\n\n"
        "Endless Summer Vacation\n\n℗ 2023 Columbia Records, a Division of Sony Music "
        "Entertainment\n\nReleased on: 2023-01-13\n\nAuto-generated by YouTube."
    )
    labels, year = songfacts.from_description(art_track)
    assert labels[0].startswith("Columbia Records") and labels[1] == "Sony Music Entertainment"
    assert year == "2023"
    licensed = "℗ 2023 Smiley Miley, Inc. under exclusive license to Columbia Records"
    assert songfacts.from_description(licensed) == (["Columbia Records"], "2023")
    labels, year = songfacts.from_description("(P) 2009 Interscope Records\nmore words")
    assert labels == ["Interscope Records"] and year == "2009"
    assert songfacts.from_description("just a fan page caption 🎵 Song - Artist") == ([], None)


def test_only_a_labels_own_channel_names_the_label():
    assert songfacts.from_uploader("Sony Music India") == "Sony Music India"
    assert songfacts.from_uploader("T-Series") == "T-Series"
    assert songfacts.from_uploader("Epic Rap Battles of History") == ""
    assert songfacts.from_uploader("Lady Gaga") == ""
    assert songfacts.from_uploader("") == ""


def test_a_majors_label_wins_over_its_partners():
    assert songfacts.pick_label(["Streamline Records", "KonLive", "Interscope Records"]) == (
        "Interscope Records",
        "UMG",
    )
    assert songfacts.pick_label(["Polystar"]) == ("Polystar", "other")
    assert songfacts.pick_label([]) == ("", "")


def musicbrainz_of(recordings: list[dict], releases: list[dict], asked: list):
    def reply(request: httpx.Request) -> httpx.Response:
        asked.append(request)
        if request.url.path.endswith("/recording"):
            return httpx.Response(200, json={"recordings": recordings})
        return httpx.Response(200, json={"releases": releases})

    return httpx.MockTransport(reply)


LUNA = [
    {"title": "Luna llena", "first-release-date": "2015-10-07",
     "releases": [{"id": "r0", "status": "Official", "date": "2015-10-07"}]},
    {"title": "LUNA", "first-release-date": "2023-12-01", "releases": [
        {"id": "r1", "status": "Official", "date": "2023-12-01"},
        {"id": "r2", "status": "Promotion", "date": "2023-11-01"},
        {"id": "r3", "status": "Official", "date": "2023-11-20",
         "release-group": {"secondary-types": ["Compilation"]}},
    ]},
]  # fmt: skip
LUNA_RELEASES = [
    {"id": "r1", "label-info": [{"label": {"name": "Universal Music Latin Entertainment"}}]}
]


def test_musicbrainz_gives_the_year_and_the_earliest_official_releases_labels():
    asked = []
    found = songfacts.musicbrainz("Luna", "Feid", musicbrainz_of(LUNA, LUNA_RELEASES, asked))
    assert found == {
        "year": "2023", "labels": ["Universal Music Latin Entertainment"], "complete": True,
    }  # fmt: skip
    assert asked[0].url.params["query"] == 'recording:"Luna" AND artist:"Feid"'
    # Only the song's own official release, not "Luna llena", a promo or a hits album.
    assert asked[1].url.params["query"] == "reid:r1"
    assert "agentic-editor" in asked[0].headers["user-agent"]


def test_a_songs_year_comes_from_takes_under_its_own_name_first():
    found = [
        {"title": "Shape of You (DJ Inko remix)", "first-release-date": "2015-01-30"},
        {"title": "Shape of You", "first-release-date": "2017-01-06"},
    ]
    transport = musicbrainz_of(found, [], [])
    assert songfacts.musicbrainz("Shape of You", "Ed Sheeran", transport)["year"] == "2017"
    remix_only = musicbrainz_of(found[:1], [], [])
    assert songfacts.musicbrainz("Shape of You", "Ed Sheeran", remix_only)["year"] == "2015"


def test_musicbrainz_out_of_reach_or_too_busy_is_no_answer():
    busy = []

    def reply(request):
        busy.append(request)
        return httpx.Response(503)

    assert songfacts.musicbrainz("Luna", "Feid", httpx.MockTransport(reply)) is None
    assert len(busy) == 1 + len(songfacts.BUSY_WAITS)  # asked again after each wait

    def down(request):
        raise httpx.ConnectError("offline")

    assert songfacts.musicbrainz("Luna", "Feid", httpx.MockTransport(down)) is None


def test_busy_a_moment_is_asked_again():
    replies = iter([httpx.Response(503), httpx.Response(200, json={"recordings": []})])
    found = songfacts.musicbrainz("Luna", "Feid", httpx.MockTransport(lambda r: next(replies)))
    assert found == {"year": None, "labels": [], "complete": True}


def test_an_answer_cut_short_gives_the_year_but_isnt_kept(tmp_path):
    asked = []

    def reply(request):
        asked.append(request)
        if request.url.path.endswith("/recording"):
            return httpx.Response(200, json={"recordings": LUNA})
        return httpx.Response(500)

    transport = httpx.MockTransport(reply)
    found = songfacts.remembered("Luna", "Feid", tmp_path, transport)
    assert found == {"year": "2023", "labels": [], "complete": False}
    songfacts.remembered("Luna", "Feid", tmp_path, transport)
    assert len(asked) == 4  # nothing kept: asked again, both times recording and release


def test_its_labels_are_kept_and_none_found_is_asked_again_after_a_week(tmp_path, monkeypatch):
    asked = []
    transport = musicbrainz_of(LUNA, LUNA_RELEASES, asked)
    first = songfacts.remembered("Luna", "Feid", tmp_path, transport)
    assert songfacts.remembered("Luna", "Feid", tmp_path, transport)["labels"] == first["labels"]
    assert len(asked) == 2  # the recording, then its release; the second time none
    unknown = musicbrainz_of([], [], asked)
    assert songfacts.remembered("Nada", "Nadie", tmp_path, unknown)["labels"] == []
    assert songfacts.remembered("Nada", "Nadie", tmp_path, unknown)["labels"] == []
    assert len(asked) == 3
    clock = songfacts.time.time() + songfacts.STALE + 1
    monkeypatch.setattr(songfacts.time, "time", lambda: clock)
    songfacts.remembered("Nada", "Nadie", tmp_path, unknown)
    assert len(asked) == 4
    # Without asking: only what is kept.
    assert songfacts.remembered("Otra", "Nadie", tmp_path, unknown, ask=False) is None
    assert len(asked) == 4


def test_what_the_video_says_comes_before_musicbrainz(tmp_path):
    asked = []
    transport = musicbrainz_of(LUNA, LUNA_RELEASES, asked)
    rimas = {"label": "Rimas Entertainment"}
    heard = songfacts.look_up("Luna", "Feid", heard=rimas, cache_dir=tmp_path, transport=transport)
    assert (heard.label, heard.group, heard.label_from) == (rimas["label"], "other", "Shazam")
    assert (heard.year, heard.year_from) == ("2023", "MusicBrainz")  # still asked for the year
    described = songfacts.look_up(
        "Kesariya", "Arijit Singh", description="℗ 2022 Sony Music Entertainment India Pvt. Ltd.",
        year="2022", year_from="notes", cache_dir=tmp_path, transport=transport,
    )  # fmt: skip
    assert described.group == "Sony" and described.label_from == "YouTube"
    assert described.year_from == "notes"
    assert len(asked) == 2  # label and year both known: MusicBrainz wasn't asked about it
    nothing = musicbrainz_of([], [], asked)
    channel = songfacts.look_up(
        "Tum Hi Ho", "Arijit Singh", uploader="T-Series", cache_dir=tmp_path, transport=nothing
    )
    assert (channel.label, channel.group, channel.year) == ("T-Series", "other", None)
    looked = songfacts.look_up("Luna", "Feid", cache_dir=tmp_path, transport=transport)
    assert (looked.label, looked.group, looked.label_from) == (
        "Universal Music Latin Entertainment", "UMG", "MusicBrainz",
    )  # fmt: skip
    assert looked.line() == "Luna by Feid, 2023, Universal Music Latin Entertainment (UMG)"


def test_a_song_without_its_artist_isnt_looked_up(tmp_path):
    asked = []
    found = songfacts.look_up("Luna", "", cache_dir=tmp_path,
                              transport=musicbrainz_of(LUNA, LUNA_RELEASES, asked))  # fmt: skip
    assert asked == [] and found.group == "" and found.year is None


def test_shazams_year_and_the_art_tracks_come_last(tmp_path):
    unknown = musicbrainz_of([], [], [])
    heard = songfacts.look_up("A", "B", heard={"released": "2024"}, cache_dir=tmp_path,
                              transport=unknown)  # fmt: skip
    assert (heard.year, heard.year_from) == ("2024", "Shazam")
    said = songfacts.look_up("A", "B", description="Released on: 2019-04-02", cache_dir=tmp_path,
                             transport=unknown)  # fmt: skip
    assert (said.year, said.year_from) == ("2019", "YouTube")


def test_new_is_the_last_three_years():
    assert songfacts.is_new("2023", 2026) and songfacts.is_new("2026", 2026)
    assert not songfacts.is_new("2022", 2026)
    assert not songfacts.is_new(None, 2026) and not songfacts.is_new("", 2026)
